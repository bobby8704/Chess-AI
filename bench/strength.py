def cmd_run(label, sims, workers, threads, limit, uniform=False):
    suite = load_suite("acpl")
    entries = suite["positions"][:limit] if limit else suite["positions"]
    print(f"ACPL run '{label}': {len(entries)} positions, {sims} sims, "
          f"{workers} workers x {threads} thread(s), Stockfish depth {suite['ref_depth']}"
          + ("   [UNIFORM CONTROL: no network]" if uniform else ""))

    rows, dt = _run_pool(_acpl_one, entries, sims, workers, threads, label, uniform)
    losses = [r["loss"] for r in rows]
    mean, sd, se = summarize(losses)
    agree = sum(r["agree"] for r in rows) / len(rows) * 100
    blunders = sum(1 for x in losses if x >= BLUNDER_CP) / len(rows) * 100
    ms = sorted(r["ms"] for r in rows)

    out = {
        "label": label, "sims": sims, "n": len(rows), "uniform": uniform,
        "ref_depth": suite["ref_depth"],
        "acpl": round(mean, 2), "sd": round(sd, 2), "se": round(se, 2),
        "agreement_pct": round(agree, 2),
        "blunder_pct": round(blunders, 2),
        "median_ms": ms[len(ms) // 2],
        "wall_s": round(dt, 1),
        "rows": rows,
    }
    os.makedirs(RESULTS_DIR, exist_ok=True)
    with open(os.path.join(RESULTS_DIR, f"strength_{label}.json"), "w") as f:
        json.dump(out, f)

    print(f"\n  ACPL              {mean:8.1f} cp   (sd {sd:.1f}, se {se:.1f})")
    print(f"  Stockfish top-1   {agree:8.1f} %")
    print(f"  blunders >={BLUNDER_CP}cp   {blunders:8.1f} %")
    print(f"  median move time  {ms[len(ms)//2]:8.0f} ms")
    print(f"  wall clock        {dt:8.0f} s")
    # Upper bound only: this uses the spread of the losses themselves. Two similar
    # arms agree on most positions, so their paired DIFFERENCES have a much smaller
    # sd and need far fewer positions. `compare` reports the real figure.
    print(f"\n  <= {n_for_delta(sd, 20)} paired positions to resolve 20cp "
          f"(loose upper bound; compare reports the true N)")
    return out


def cmd_mate(label, sims, workers, threads, limit):
    suite = load_suite("mate1")
    entries = suite["positions"][:limit] if limit else suite["positions"]
    if not entries:
        raise SystemExit("mate suite is empty — rebuild with --mate")
    print(f"Mate-in-1 '{label}': {len(entries)} positions, {sims} sims")
    rows, dt = _run_pool(_mate_one, entries, sims, workers, threads, label)
    found = sum(r["found"] for r in rows)
    out = {"label": label, "sims": sims, "n": len(rows), "found": found,
           "pct": round(found / len(rows) * 100, 1), "wall_s": round(dt, 1),
           "rows": rows}
    os.makedirs(RESULTS_DIR, exist_ok=True)
    with open(os.path.join(RESULTS_DIR, f"mate_{label}.json"), "w") as f:
        json.dump(out, f)
    print(f"\n  mate-in-1 found   {found}/{len(rows)}  ({out['pct']}%)")
    print(f"  wall clock        {dt:.0f} s")
    return out


def cmd_compare(a_label, b_label):
    def load(l):
        p = os.path.join(RESULTS_DIR, f"strength_{l}.json")
        if not os.path.exists(p):
            raise SystemExit(f"missing {p}")
        with open(p) as f:
            return json.load(f)

    a, b = load(a_label), load(b_label)
    amap = {r["name"]: r for r in a["rows"]}
    bmap = {r["name"]: r for r in b["rows"]}
    shared = sorted(set(amap) & set(bmap))
    if not shared:
        raise SystemExit("no shared positions between the two runs")

    diffs = [bmap[n]["loss"] - amap[n]["loss"] for n in shared]
    mean, sd, se = summarize(diffs)
    t = mean / se if se else 0.0
    p = 2 * (1 - normal_cdf(abs(t)))
    lo, hi = mean - 1.96 * se, mean + 1.96 * se
    changed = sum(1 for n in shared if amap[n]["move"] != bmap[n]["move"])

    print(f"\nPAIRED COMPARISON on {len(shared)} shared positions")
    print(f"  (negative favours {b_label}: lower centipawn loss is better)\n")
    print(f"  {a_label:<24} ACPL {a['acpl']:8.1f} cp   agree {a['agreement_pct']:5.1f}%   "
          f"blunders {a['blunder_pct']:5.1f}%   {a['median_ms']:6.0f} ms")
    print(f"  {b_label:<24} ACPL {b['acpl']:8.1f} cp   agree {b['agreement_pct']:5.1f}%   "
          f"blunders {b['blunder_pct']:5.1f}%   {b['median_ms']:6.0f} ms")
    print(f"\n  paired difference   {mean:+8.2f} cp   (se {se:.2f}, sd {sd:.1f})")
    print(f"  95% CI              [{lo:+.2f}, {hi:+.2f}] cp")
    print(f"  t = {t:+.2f}   p = {p:.4f}")
    print(f"  moves differing     {changed}/{len(shared)} ({changed/len(shared)*100:.1f}%)")

    print()
    if p < 0.05:
        better = b_label if mean < 0 else a_label
        print(f"  SIGNIFICANT at alpha=0.05 — {better} is stronger on this suite.")
    else:
        need = n_for_delta(sd, 20)
        print(f"  NOT SIGNIFICANT. This does NOT mean the arms are equal — it means this")
        print(f"  experiment could not tell. Resolving a 20cp difference at this variance")
        print(f"  needs {need} paired positions; you ran {len(shared)}.")
        detectable = 2.8 * sd / math.sqrt(len(shared))
        print(f"  Smallest difference {len(shared)} positions could detect: ~{detectable:.0f} cp.")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    default_workers = max(1, (os.cpu_count() or 4) - 2)

    b = sub.add_parser("build", help="generate and cache the frozen position suites")
    b.add_argument("--games", type=int, default=700)
    b.add_argument("--per-game", type=int, default=2)
    b.add_argument("--mate", action="store_true", default=True,
                   help="also collect mate-in-1 positions")
    b.add_argument("--workers", type=int, default=default_workers)

    r = sub.add_parser("run", help="measure ACPL for one engine configuration")
    r.add_argument("label")
    r.add_argument("--sims", type=int, default=600)
    r.add_argument("--workers", type=int, default=default_workers)
    r.add_argument("--threads", type=int, default=1)
    r.add_argument("--limit", type=int, default=None)
    r.add_argument("--uniform", action="store_true",
                   help="positive control: search with no network (uniform priors). "
                        "Must measure clearly worse; if it does not, the harness has "
                        "no power and its null results mean nothing.")

    m = sub.add_parser("mate", help="mate-in-1 detection rate")
    m.add_argument("label")
    m.add_argument("--sims", type=int, default=200)
    m.add_argument("--workers", type=int, default=default_workers)
    m.add_argument("--threads", type=int, default=1)
    m.add_argument("--limit", type=int, default=None)

    c = sub.add_parser("compare", help="paired comparison of two runs")
    c.add_argument("a_label")
    c.add_argument("b_label")

    args = ap.parse_args()
    if args.cmd == "build":
        build(args.games, args.per_game, args.mate, args.workers)
    elif args.cmd == "run":
        cmd_run(args.label, args.sims, args.workers, args.threads, args.limit,
                args.uniform)
    elif args.cmd == "mate":
        cmd_mate(args.label, args.sims, args.workers, args.threads, args.limit)
    else:
        cmd_compare(args.a_label, args.b_label)


if __name__ == "__main__":
    main()
