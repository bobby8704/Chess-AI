"""
Objective strength measurement for the MCTS engine.

This project has never had one. arena.py cannot instantiate MCTSPlayer at all, the
trainer has no held-out split, and the logged p_loss is in-sample — so "is the engine
stronger than it was?" has never been answerable. Everything in Track B (the mate-in-1
blunder fix, PUCT/FPU, int8 quantisation, time budgets, a smaller trunk) changes move
selection, and none of it can be shipped responsibly without this.

Metric: average centipawn loss (ACPL) against Stockfish at fixed depth.

    loss = max(0, eval_before - eval_after)     both from the mover's perspective

Two properties make the comparison trustworthy:

  * PAIRED. Both arms are measured on the identical frozen position set, so the
    comparison is on per-position differences and the (large) variation between
    positions cancels instead of drowning the effect.
  * DETERMINISTIC. Stockfish is sent ucinewgame before every analysis. Without it the
    transposition table persists and the same position scores 48/47/51 cp on repeat
    calls; with it, the same value every time.

Positions are generated by letting Stockfish play both sides at shallow depth with
randomised top-k selection, so they are real middlegames rather than random-legal-move
noise, and every position's baseline eval and best move are cached at build time. That
halves the Stockfish work per arm and keeps the reference fixed across runs.

Beware underpowered results. Per-position loss has a standard deviation near 90cp, so
a 50-position run cannot resolve anything; `compare` always prints the N required for
the variance it actually observed. Treat a non-significant result as "not measured",
never as "no difference".

Usage:
    python bench/strength.py build --games 700 --mate 120
    python bench/strength.py run baseline-600 --sims 600
    python bench/strength.py run candidate-600 --sims 600
    python bench/strength.py compare baseline-600 candidate-600
    python bench/strength.py mate baseline --sims 200
"""

import argparse
import json
import math
import os
import random
import sys
import time
from multiprocessing import Pool

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import chess  # noqa: E402
import chess.engine  # noqa: E402

SF_PATH = os.path.join(ROOT, "stockfish", "stockfish.exe")
SUITE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "suites")
RESULTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")

REF_DEPTH = 16          # Stockfish reference depth for scoring
GEN_DEPTH = 6           # shallow depth used only to generate realistic games
MIN_PIECES = 12         # stay clear of the <=7-piece tablebase HTTP probe
MIN_LEGAL = 8
MAX_LEGAL = 48
BLUNDER_CP = 200        # a "blunder" for reporting purposes
LOSS_CAP = 1000         # cap so a single mate score cannot dominate the mean
MATE_SCORE = 100000


# ---------------------------------------------------------------------------
# Stockfish helpers
# ---------------------------------------------------------------------------

def open_engine(hash_mb: int = 32):
    eng = chess.engine.SimpleEngine.popen_uci(SF_PATH)
    eng.configure({"Threads": 1, "Hash": hash_mb})
    return eng


def analyse(eng, board, depth=REF_DEPTH, multipv=None):
    """
    Analyse at fixed depth with a CLEAN transposition table.

    The fresh `game` object makes python-chess send ucinewgame, which is what makes
    the result reproducible; without it repeated analyses of one position disagree by
    several centipawns because the TT carries over.
    """
    kwargs = {"game": object()}
    if multipv:
        kwargs["multipv"] = multipv
    return eng.analyse(board, chess.engine.Limit(depth=depth), **kwargs)


def pov_cp(info, board):
    """Score in centipawns from the perspective of the side to move on `board`."""
    return info["score"].pov(board.turn).score(mate_score=MATE_SCORE)


def rebuild(moves_uci):
    """Rebuild a board WITH its move stack (never chess.Board(fen) — see bench/positions.py)."""
    b = chess.Board()
    for u in moves_uci:
        b.push(chess.Move.from_uci(u))
    return b


def _playable(board):
    if board.is_game_over():
        return False
    if chess.popcount(board.occupied) < MIN_PIECES:
        return False
    return MIN_LEGAL <= board.legal_moves.count() <= MAX_LEGAL


# ---------------------------------------------------------------------------
# Suite construction
# ---------------------------------------------------------------------------

def _gen_game(eng, rng, max_ply):
    """
    Play one game with Stockfish choosing among its top-3 shallow moves at random.

    Random-legal play produces positions no real game would ever reach, which makes an
    ACPL number meaningless as an absolute. Shallow Stockfish with randomised top-k
    stays in plausible territory while still giving enough variety to fill a suite.
    """
    board = chess.Board()
    while len(board.move_stack) < max_ply and not board.is_game_over():
        n = min(3, board.legal_moves.count())
        if n == 0:
            break
        try:
            infos = analyse(eng, board, depth=GEN_DEPTH, multipv=n)
        except Exception:
            break
        moves = [i["pv"][0] for i in infos if i.get("pv")]
        if not moves:
            break
        # Weight toward the best move so games stay coherent, but not deterministically.
        weights = [0.6, 0.25, 0.15][:len(moves)]
        board.push(rng.choices(moves, weights=weights)[0])
    return board


def _build_chunk(args):
    """Worker: generate games from one seed range and return scored positions."""
    seed, n_games, per_game, want_mate = args
    rng = random.Random(seed)
    eng = open_engine()
    positions, mates = [], []
    try:
        for g in range(n_games):
            max_ply = rng.randint(20, 70)
            board = _gen_game(eng, rng, max_ply)
            history = board.move_stack[:]

            # Sample distinct plies from this game.
            candidates = []
            for _ in range(per_game * 3):
                if len(history) < 12:
                    break
                cut = rng.randint(12, len(history))
                sub = [m.uci() for m in history[:cut]]
                b = rebuild(sub)
                if _playable(b):
                    candidates.append((sub, b))
                if len(candidates) >= per_game:
                    break

            for sub, b in candidates[:per_game]:
                info = analyse(eng, b, depth=REF_DEPTH)
                pv = info.get("pv")
                if not pv:
                    continue
                positions.append({
                    "moves": sub,
                    "fen": b.fen(),
                    "ply": len(sub),
                    "n_legal": b.legal_moves.count(),
                    "n_pieces": chess.popcount(b.occupied),
                    "base_cp": pov_cp(info, b),
                    "sf_best": pv[0].uci(),
                })

            if want_mate:
                mates.extend(_gen_mate_positions(eng, rng))
    finally:
        eng.quit()
    return positions, mates


def _mate_in_1_moves(board):
    """All moves that deliver immediate checkmate. Cheap: push, test, pop."""
    out = []
    for mv in board.legal_moves:
        board.push(mv)
        if board.is_checkmate():
            out.append(mv.uci())
        board.pop()
    return out


def _gen_mate_positions(eng, rng, max_ply=120):
    """
    Produce positions where the side to move has mate in 1.

    Stockfish playing itself almost never allows one, so this pits a strong side
    (shallow Stockfish best move) against a weak side (random legal), which reaches
    mating attacks quickly. Positions are kept at >= 8 pieces so the engine's own
    search has to find the mate — below that, select_move short-circuits to the
    Lichess tablebase and the test would measure the network, not the engine.
    """
    found = []
    board = chess.Board()
    strong = rng.choice([chess.WHITE, chess.BLACK])
    while len(board.move_stack) < max_ply and not board.is_game_over():
        if board.turn == strong and chess.popcount(board.occupied) >= 8:
            mating = _mate_in_1_moves(board)
            if mating:
                found.append({
                    "moves": [m.uci() for m in board.move_stack],
                    "fen": board.fen(),
                    "mating_moves": mating,
                    "n_legal": board.legal_moves.count(),
                    "n_pieces": chess.popcount(board.occupied),
                })
                return found  # one per game keeps the sample independent

        if board.turn == strong:
            try:
                info = analyse(eng, board, depth=GEN_DEPTH)
                mv = info["pv"][0]
            except Exception:
                break
        else:
            mv = rng.choice(list(board.legal_moves))
        board.push(mv)
    return found


def build(n_games, per_game, want_mate, workers, seed=20260805):
    os.makedirs(SUITE_DIR, exist_ok=True)
    chunks = []
    per_worker = max(1, n_games // workers)
    for w in range(workers):
        chunks.append((seed + w * 7919, per_worker, per_game, want_mate))

    t0 = time.perf_counter()
    positions, mates = [], []
    with Pool(workers) as pool:
        for i, (p, m) in enumerate(pool.imap_unordered(_build_chunk, chunks)):
            positions.extend(p)
            mates.extend(m)
            print(f"  worker {i + 1}/{len(chunks)} done: "
                  f"{len(positions)} positions, {len(mates)} mate-in-1")

    # Deterministic order regardless of which worker finished first.
    positions.sort(key=lambda e: (len(e["moves"]), e["fen"]))
    mates.sort(key=lambda e: (len(e["moves"]), e["fen"]))
    for i, e in enumerate(positions):
        e["name"] = f"p{i:04d}"
    for i, e in enumerate(mates):
        e["name"] = f"m{i:04d}"

    with open(os.path.join(SUITE_DIR, "acpl.json"), "w") as f:
        json.dump({"ref_depth": REF_DEPTH, "positions": positions}, f)
    with open(os.path.join(SUITE_DIR, "mate1.json"), "w") as f:
        json.dump({"positions": mates}, f)

    dt = time.perf_counter() - t0
    plies = [e["ply"] for e in positions]
    print(f"\nbuilt {len(positions)} ACPL positions and {len(mates)} mate-in-1 positions "
          f"in {dt:.0f}s")
    if plies:
        print(f"  ply range {min(plies)}-{max(plies)}, median {sorted(plies)[len(plies)//2]}")
        print(f"  pieces {min(e['n_pieces'] for e in positions)}-"
              f"{max(e['n_pieces'] for e in positions)}, "
              f"legal {min(e['n_legal'] for e in positions)}-"
              f"{max(e['n_legal'] for e in positions)}")


def load_suite(name):
    path = os.path.join(SUITE_DIR, f"{name}.json")
    if not os.path.exists(path):
        raise SystemExit(f"no suite at {path} — run: python bench/strength.py build")
    with open(path) as f:
        return json.load(f)


