_ENGINE = None
_MODEL = None
_SIMS = None
_UNIFORM = False


def _init_worker(sims, threads, uniform=False):
    global _ENGINE, _MODEL, _SIMS, _UNIFORM
    # Set BEFORE the ONNX session is created: with many workers, one inference thread
    # each is right — oversubscribing turns a parallel sweep into a slow serial one.
    os.environ["CHESS_NUM_THREADS"] = str(threads)
    _SIMS = sims
    _UNIFORM = uniform
    _ENGINE = open_engine()

    if uniform:
        # Deliberate control arm: search with no network at all (uniform priors).
        # It must come out clearly worse. If a comparison against this is NOT
        # significant, the harness lacks the power to detect anything and no null
        # result from it should be believed.
        os.environ["CHESS_USE_ONNX"] = "0"
        _MODEL = None
        return

    from inference import get_onnx_session
    session = get_onnx_session()
    model = None
    if session is None:
        from neural_network import load_dual_model, DEFAULT_CKPT_PATH
        model = load_dual_model(DEFAULT_CKPT_PATH)
    _MODEL = model
    if session is None and model is None:
        raise RuntimeError("no model available; refusing to measure a random policy")


def _make_player():
    """Mirror app.py: a fresh player per move, temperature 0, no Dirichlet noise."""
    from mcts import MCTSPlayer, MCTSConfig
    return MCTSPlayer(model=_MODEL,
                      config=MCTSConfig(num_simulations=_SIMS, temperature=0,
                                        add_noise=False))


def _acpl_one(entry):
    board = rebuild(entry["moves"])
    t0 = time.perf_counter()
    move = _make_player().select_move(board)
    ms = (time.perf_counter() - t0) * 1000
    if move is None:
        return None

    board.push(move)
    if board.is_checkmate():
        after_cp = MATE_SCORE          # we just delivered mate
    elif board.is_game_over():
        after_cp = 0                   # stalemate / insufficient material / etc
    else:
        after_cp = -pov_cp(analyse(_ENGINE, board), board)

    loss = min(LOSS_CAP, max(0, entry["base_cp"] - after_cp))
    return {
        "name": entry["name"],
        "move": move.uci(),
        "loss": loss,
        "agree": move.uci() == entry["sf_best"],
        "ms": round(ms, 1),
    }


def _mate_one(entry):
    board = rebuild(entry["moves"])
    t0 = time.perf_counter()
    move = _make_player().select_move(board)
    ms = (time.perf_counter() - t0) * 1000
    return {
        "name": entry["name"],
        "move": move.uci() if move else None,
        "found": bool(move) and move.uci() in entry["mating_moves"],
        "ms": round(ms, 1),
    }


def _run_pool(fn, entries, sims, workers, threads, label, uniform=False):
    t0 = time.perf_counter()
    out = []
    with Pool(workers, initializer=_init_worker,
              initargs=(sims, threads, uniform)) as pool:
        for i, r in enumerate(pool.imap_unordered(fn, entries, chunksize=1), 1):
            if r is not None:
                out.append(r)
            if i % 50 == 0 or i == len(entries):
                el = time.perf_counter() - t0
                rate = i / el
                print(f"  {i}/{len(entries)}  {el:5.0f}s elapsed, "
                      f"{(len(entries) - i) / rate:5.0f}s left", flush=True)
    out.sort(key=lambda r: r["name"])
    return out, time.perf_counter() - t0


# ---------------------------------------------------------------------------
# Statistics (no scipy in this venv)
# ---------------------------------------------------------------------------

def normal_cdf(z):
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


def summarize(losses):
    n = len(losses)
    mean = sum(losses) / n
    var = sum((x - mean) ** 2 for x in losses) / (n - 1) if n > 1 else 0.0
    sd = math.sqrt(var)
    return mean, sd, sd / math.sqrt(n) if n else 0.0


def n_for_delta(sd, delta, power=0.80, alpha=0.05):
    """Paired-sample N needed to detect `delta` given per-pair sd."""
    z_a, z_b = 1.959963985, 0.8416212336
    return math.ceil((z_a + z_b) ** 2 * sd ** 2 / delta ** 2)


